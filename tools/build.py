import json,sys
d=json.load(open(sys.argv[1]))
rows=[l.split('|') for l in open(sys.argv[2],encoding='utf8').read().splitlines() if l]
idx={r[0].lower():i for i,r in enumerate(rows)}
assert len(idx)==len(rows)
miss=[k for k in list(d['rec'])+d['base'] if k not in idx]
assert not miss,miss
rec={};conf=[]
for res,ps in d['rec'].items():
    for a,b in ps:
        a,b=sorted((idx[a],idx[b]));k=f'{a},{b}'
        rec.setdefault(k,[])
        if idx[res] not in rec[k]: rec[k].append(idx[res])
print('conflicts',conf)
base=[idx[b] for b in d['base']+['freddo','luce']]
js='// generated by build.py from combinations.txt\nconst EL='+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\nconst BASE='+json.dumps(base)+';\nconst REC='+json.dumps(rec,separators=(',',':'))+';\n'
open('data.js','w',encoding='utf8').write(js)
print(len(rows),len(rec))
